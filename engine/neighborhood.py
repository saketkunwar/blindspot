"""T-1.7 Conceptual-neighborhood graph (derived, not hand-written).

Generated by ``engine/tools/generate_neighborhood.py``; this module loads the
artifact and answers adjacency / shortest-path queries for continuity (T-2.1).
"""
from __future__ import annotations

import json
import pathlib
from collections import deque

_DATA = json.loads((pathlib.Path(__file__).parent / "neighborhood.json").read_text())
NEIGHBORS: dict[str, list[str]] = _DATA["neighbors"]


def neighbors(relation: str) -> list[str]:
    """Relations reachable by one continuous deformation step."""
    return list(NEIGHBORS[relation])


def shortest_path(frm: str, to: str) -> list[str]:
    """Shortest chain of missing intermediate states (exclusive of endpoints)."""
    if frm == to:
        return []
    prev: dict[str, str | None] = {frm: None}
    queue = deque([frm])
    while queue:
        cur = queue.popleft()
        for nb in NEIGHBORS[cur]:
            if nb not in prev:
                prev[nb] = cur
                queue.append(nb)
                if nb == to:
                    queue.clear()
                    break
    if to not in prev:
        return []
    path = [to]
    while prev[path[-1]] != frm and prev[path[-1]] is not None:
        path.append(prev[path[-1]])  # type: ignore[arg-type]
    path.append(frm)
    return path[::-1][1:-1]
